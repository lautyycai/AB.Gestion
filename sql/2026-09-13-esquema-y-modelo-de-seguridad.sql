create or replace function public.mi_rol()
 returns text
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select coalesce((select rol from public.usuarios where id = auth.uid()), '')
$function$;

create or replace function public.mi_dupla()
 returns text
 language sql
 stable security definer
 set search_path to 'public'
as $function$ select dupla_asignada from public.usuarios where id = auth.uid() $function$;

create or replace function public.tiene_dupla(p_ejecutivo text)
 returns boolean
 language sql
 stable
 set search_path to 'public'
as $function$
  select p_ejecutivo = any(coalesce((select dupla_asignada from usuarios where id = auth.uid()), '{}'::text[]))
$function$;

create or replace function public.es_admin()
 returns boolean
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select exists (select 1 from usuarios where id = auth.uid() and rol = 'admin');
$function$;

create or replace function public.es_jefe()
 returns boolean
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select exists (select 1 from usuarios where id = auth.uid() and rol = 'jefe');
$function$;

-- Genérica: cubre las 7 tablas auditadas (todas menos audit_log en sí y
-- catalogos... ver PASO 4 para cuáles la usan). registro_id se castea a
-- ::text para no depender del tipo de la PK de cada tabla (bigint en la
-- mayoría, uuid en usuarios).
create or replace function public.fn_audit_log()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_usuario_id uuid := auth.uid();
  v_usuario_nombre text;
begin
  select nombre_completo into v_usuario_nombre from public.usuarios where id = v_usuario_id;
  if (tg_op = 'DELETE') then
    insert into public.audit_log (usuario_id, usuario_nombre, accion, tabla, registro_id, datos_anteriores)
    values (v_usuario_id, v_usuario_nombre, 'delete', tg_table_name, old.id::text, to_jsonb(old));
    return old;
  elsif (tg_op = 'UPDATE') then
    insert into public.audit_log (usuario_id, usuario_nombre, accion, tabla, registro_id, datos_anteriores, datos_nuevos)
    values (v_usuario_id, v_usuario_nombre, 'update', tg_table_name, new.id::text, to_jsonb(old), to_jsonb(new));
    return new;
  elsif (tg_op = 'INSERT') then
    insert into public.audit_log (usuario_id, usuario_nombre, accion, tabla, registro_id, datos_nuevos)
    values (v_usuario_id, v_usuario_nombre, 'insert', tg_table_name, new.id::text, to_jsonb(new));
    return new;
  end if;
  return null;
end;
$function$;

create or replace function public.fn_bump_version()
 returns trigger
 language plpgsql
 set search_path to 'public'
as $function$
begin
  new.version := coalesce(old.version, 0) + 1;
  return new;
end;
$function$;

create or replace function public.fn_recalcular_total_produccion()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_produccion_id bigint;
  v_total numeric;
begin
  v_produccion_id := coalesce(new.produccion_id, old.produccion_id);
  select coalesce(sum(cantidad),0) into v_total from public.produccion_companias where produccion_id = v_produccion_id;
  update public.producciones set total_polizas = v_total where id = v_produccion_id;
  return coalesce(new, old);
end;
$function$;

-- BEFORE INSERT/UPDATE: completa el autor desde la sesión (auth.uid()),
-- ignorando lo que mande el navegador. Antes de esto, usuario_nombre lo
-- mandaba el frontend como texto libre y era suplantable.
create or replace function public.fn_reportes_autor()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'pg_catalog'
as $function$
begin
  if tg_op = 'INSERT' then
    new.usuario_id := auth.uid();
    select u.nombre_completo into new.usuario_nombre
      from public.usuarios u
     where u.id = auth.uid();
    if new.usuario_nombre is null then
      new.usuario_nombre := 'Usuario';
    end if;
  elsif tg_op = 'UPDATE' then
    new.usuario_id := old.usuario_id;
    new.usuario_nombre := old.usuario_nombre;
  end if;
  return new;
end;
$function$;

-- Event trigger: activa RLS automáticamente en cualquier tabla nueva del
-- esquema public, como red de seguridad ante el olvido.
create or replace function public.rls_auto_enable()
 returns event_trigger
 language plpgsql
 security definer
 set search_path to 'pg_catalog'
as $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

create or replace function public.crear_produccion_completa(p_pas_id bigint, p_ramo text, p_trimestre text, p_ejecutivo text, p_organizador text, p_fecha date, p_total integer, p_detalle jsonb)
 returns bigint
 language plpgsql
 set search_path to 'public'
as $function$
declare
  v_id bigint;
begin
  insert into public.producciones
    (pas_id, ramo, trimestre, ejecutivo, organizador, ultima_fecha, total_polizas)
  values
    (p_pas_id, p_ramo, p_trimestre, p_ejecutivo, p_organizador, p_fecha, p_total)
  returning id into v_id;

  insert into public.produccion_companias (produccion_id, compania, cantidad)
  select v_id, d->>'compania', (d->>'cantidad')::int
    from jsonb_array_elements(p_detalle) as d;

  return v_id;
end;
$function$;

create or replace function public.guardar_produccion_completa(p_produccion_id bigint, p_ramo text, p_trimestre text, p_organizador text, p_fecha date, p_total integer, p_detalle jsonb, p_version integer default null::integer)
 returns void
 language plpgsql
 set search_path to 'public'
as $function$
begin
  update public.producciones
     set ramo          = p_ramo,
         trimestre     = p_trimestre,
         organizador   = p_organizador,
         ultima_fecha  = p_fecha,
         total_polizas = p_total
   where id = p_produccion_id
     and (p_version is null or version = p_version);

  if not found then
    if p_version is not null
       and exists (select 1 from public.producciones where id = p_produccion_id) then
      raise exception 'Otra persona modificó esta carga mientras la editabas. Recargá la página y volvé a aplicar tus cambios.';
    end if;

    raise exception 'No se encontró la carga, o no tenés permiso para editarla.';
  end if;

  delete from public.produccion_companias
   where produccion_id = p_produccion_id;

  insert into public.produccion_companias (produccion_id, compania, cantidad)
  select p_produccion_id, d->>'compania', (d->>'cantidad')::int
    from jsonb_array_elements(p_detalle) as d;
end;
$function$;

create or replace function public.eliminar_pas(p_pas_id bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_rol text := public.mi_rol();
  v_ejecutivo text;
  v_tiene_produccion boolean;
begin
  select ejecutivo into v_ejecutivo from productores where id = p_pas_id;
  if v_ejecutivo is null then
    raise exception 'El PAS no existe';
  end if;

  select exists(select 1 from producciones where pas_id = p_pas_id) into v_tiene_produccion;

  if v_rol = 'admin' then
    null;
  elsif v_rol = 'editor' and public.tiene_dupla(v_ejecutivo) and not v_tiene_produccion then
    null;
  elsif v_rol = 'carga_pas' and public.tiene_dupla(v_ejecutivo) and not v_tiene_produccion then
    null;
  else
    raise exception 'No tenés permiso para eliminar este PAS';
  end if;

  delete from produccion_companias where produccion_id in (select id from producciones where pas_id = p_pas_id);
  delete from producciones where pas_id = p_pas_id;
  delete from productores where id = p_pas_id;
end;
$function$;

create or replace function public.eliminar_produccion(p_produccion_id bigint)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_ejecutivo text;
  v_rol text;
begin
  select ejecutivo into v_ejecutivo from producciones where id = p_produccion_id;
  if v_ejecutivo is null then
    raise exception 'La carga no existe.';
  end if;

  select rol into v_rol from usuarios where id = auth.uid();

  if v_rol = 'admin' then
  elsif v_rol = 'editor' and public.tiene_dupla(v_ejecutivo) then
  else
    raise exception 'No tenés permiso para eliminar esta carga.';
  end if;

  delete from produccion_companias where produccion_id = p_produccion_id;
  delete from producciones where id = p_produccion_id;
end;
$function$;

create or replace function public.eliminar_producciones_pas(p_pas_id bigint)
 returns integer
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_rol text;
  v_borradas integer;
begin
  select rol into v_rol from usuarios where id = auth.uid();

  if v_rol = 'admin' then
    delete from produccion_companias
      where produccion_id in (select id from producciones where pas_id = p_pas_id);
    delete from producciones where pas_id = p_pas_id;
    get diagnostics v_borradas = row_count;
  elsif v_rol = 'editor' then
    delete from produccion_companias
      where produccion_id in (
        select id from producciones
        where pas_id = p_pas_id and public.tiene_dupla(ejecutivo)
      );
    delete from producciones where pas_id = p_pas_id and public.tiene_dupla(ejecutivo);
    get diagnostics v_borradas = row_count;
  else
    raise exception 'No tenés permiso para eliminar cargas.';
  end if;

  return v_borradas;
end;
$function$;

-- El nombre se recorta y pasa a mayúsculas antes de guardarlo (y de chequear
-- si ya existe, ignorando mayúsculas/minúsculas), para que variantes como
-- "dupla_a" / "Dupla_A" / "dupla_a " no convivan como duplas distintas.
create or replace function public.crear_dupla_propia(p_nombre text)
 returns jsonb
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_uid uuid := auth.uid();
  v_rol text := mi_rol();
  v_rows int;
  v_nombre text := upper(trim(p_nombre));
begin
  if v_rol <> 'editor' then
    raise exception 'Solo un editor puede crear una dupla propia';
  end if;

  if v_nombre is null or v_nombre = '' then
    raise exception 'El nombre de la dupla no puede estar vacío';
  end if;

  if length(v_nombre) > 40 then
    raise exception 'El nombre de la dupla es demasiado largo (máximo 40 caracteres)';
  end if;

  if exists (select 1 from catalogos where tipo = 'ejecutivo' and lower(valor) = lower(v_nombre)) then
    raise exception 'Ya existe una dupla con ese nombre';
  end if;

  insert into catalogos (tipo, valor, activo) values ('ejecutivo', v_nombre, true);

  update usuarios
  set dupla_asignada = array_append(coalesce(dupla_asignada, '{}'::text[]), v_nombre)
  where id = v_uid;
  get diagnostics v_rows = row_count;

  return jsonb_build_object('uid', v_uid, 'rol', v_rol, 'filas_actualizadas', v_rows);
end;
$function$;

create or replace function public.eliminar_dupla_admin(p_nombre text)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  if mi_rol() <> 'admin' then
    raise exception 'Solo un admin puede eliminar cualquier dupla';
  end if;

  if exists (select 1 from productores where ejecutivo = p_nombre) then
    raise exception 'No se puede borrar: hay PAS cargados con esa dupla';
  end if;

  if exists (select 1 from metas where dupla = p_nombre) then
    raise exception 'No se puede borrar: hay metas cargadas con esa dupla';
  end if;

  update usuarios
  set dupla_asignada = array_remove(dupla_asignada, p_nombre)
  where p_nombre = any(coalesce(dupla_asignada, '{}'::text[]));

  delete from catalogos where tipo = 'ejecutivo' and valor = p_nombre;
end;
$function$;

create or replace function public.eliminar_dupla_propia(p_nombre text)
 returns void
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_uid uuid := auth.uid();
  v_rol text := mi_rol();
  v_mis_duplas text[] := coalesce((select dupla_asignada from usuarios where id = v_uid), '{}'::text[]);
begin
  if v_rol <> 'editor' then
    raise exception 'Solo un editor puede eliminar una dupla propia';
  end if;

  if not (p_nombre = any(v_mis_duplas)) then
    raise exception 'Esa dupla no está entre las tuyas';
  end if;

  if array_length(v_mis_duplas, 1) <= 1 then
    raise exception 'No podés quedarte sin ninguna dupla asignada';
  end if;

  if exists (select 1 from productores where ejecutivo = p_nombre) then
    raise exception 'No se puede borrar: hay PAS cargados con esa dupla';
  end if;

  if exists (select 1 from metas where dupla = p_nombre) then
    raise exception 'No se puede borrar: hay metas cargadas con esa dupla';
  end if;

  update usuarios
  set dupla_asignada = array_remove(dupla_asignada, p_nombre)
  where id = v_uid;

  if not exists (select 1 from usuarios where p_nombre = any(coalesce(dupla_asignada, '{}'::text[]))) then
    delete from catalogos where tipo = 'ejecutivo' and valor = p_nombre;
  end if;
end;
$function$;


