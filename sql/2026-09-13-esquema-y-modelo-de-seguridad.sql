-- ============================================================================
-- PASO 5 -- Permisos: anon sin nada, authenticated acotado, funciones de
-- trigger sin EXECUTE para nadie (solo las dispara el motor internamente)
-- ============================================================================

alter default privileges in schema public revoke execute on functions from public;
alter default privileges in schema public revoke execute on functions from anon;
revoke execute on all functions in schema public from public, anon;
revoke all on all tables in schema public from public, anon;

grant select, insert, update, delete on
  public.productores, public.producciones, public.produccion_companias,
  public.catalogos, public.metas, public.usuarios, public.reportes, public.audit_log
to authenticated;

-- Helpers usados DENTRO de las policies: tienen que poder ejecutarlos
-- authenticated (y anon, para que una consulta sin sesión falle limpio en vez
-- de con "permission denied for function").
grant execute on function public.mi_rol() to authenticated, anon;
grant execute on function public.mi_dupla() to authenticated, anon;
grant execute on function public.tiene_dupla(text) to authenticated, anon;
grant execute on function public.es_admin() to authenticated, anon;
grant execute on function public.es_jefe() to authenticated, anon;

-- RPC que llama el frontend directo: EXECUTE explícito a authenticated. Su
-- protección es la validación de rol/dupla de adentro, no el permiso de
-- ejecución en sí.
grant execute on function public.crear_dupla_propia(text) to authenticated;
grant execute on function public.eliminar_dupla_propia(text) to authenticated;
grant execute on function public.eliminar_dupla_admin(text) to authenticated;
grant execute on function public.eliminar_pas(bigint) to authenticated;
grant execute on function public.eliminar_produccion(bigint) to authenticated;
grant execute on function public.eliminar_producciones_pas(bigint) to authenticated;
grant execute on function public.crear_produccion_completa(bigint,text,text,text,text,date,integer,jsonb) to authenticated;
grant execute on function public.guardar_produccion_completa(bigint,text,text,text,date,integer,jsonb,integer) to authenticated;

-- Funciones que SOLO dispara un trigger: nadie las llama por la API.
revoke execute on function public.fn_audit_log() from public, anon, authenticated;
revoke execute on function public.fn_bump_version() from authenticated;
revoke execute on function public.fn_recalcular_total_produccion() from authenticated;
