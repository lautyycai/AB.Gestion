create table public.usuarios (
  id uuid primary key default gen_random_uuid(),
  nombre_completo text not null,
  rol text,
  dupla_asignada text[]
);

create table public.catalogos (
  id bigint generated by default as identity primary key,
  tipo text not null,
  valor text,
  activo boolean,
  unique (tipo, valor)
);

create table public.productores (
  id bigint generated by default as identity primary key,
  pas_nombre text not null,
  organizacion text,
  vinculante text,
  ejecutivo text,
  telefono text,
  mail text,
  fecha_nacimiento date,
  companias_opera text,
  cantidad_polizas_vigentes integer,
  observaciones text,
  estado text,
  zona text,
  localidad_prov text,
  version integer not null default 1
);

create table public.producciones (
  id bigint generated by default as identity primary key,
  pas_id bigint not null references public.productores(id),
  ramo text,
  trimestre text,
  ejecutivo text,
  organizador text,
  total_polizas integer,
  ultima_fecha date,
  version integer not null default 1
);

-- Sin FK explícita hacia producciones: se vincula por convención vía
-- produccion_id, controlado enteramente por los RPC (nunca por el frontend
-- directo -- ver crear_produccion_completa/guardar_produccion_completa).
create table public.produccion_companias (
  id bigint generated by default as identity primary key,
  produccion_id bigint not null,
  compania text,
  cantidad integer
);

create table public.metas (
  id bigint generated by default as identity primary key,
  dupla text not null,
  trimestre text not null,
  objetivo_polizas numeric not null check (objetivo_polizas >= 0),
  creado_por uuid references public.usuarios(id),
  creado_en timestamptz not null default now(),
  unique (dupla, trimestre)
);

create table public.reportes (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null default gen_random_uuid(),
  usuario_nombre text,
  vista text,
  mensaje text,
  estado text,
  creado_en timestamptz,
  respuesta text
);

-- registro_id es text (no bigint) a propósito: usuarios.id es uuid, y una
-- columna numérica no puede guardar un uuid. No se usa para hacer joins, solo
-- para mostrarlo en pantalla, así que el tipo de dato de origen no importa.
create table public.audit_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  usuario_id uuid references public.usuarios(id),
  usuario_nombre text,
  accion text not null,
  tabla text not null,
  registro_id text,
  datos_anteriores jsonb,
  datos_nuevos jsonb
);


