-- ============================================================================
-- AB Gestión — esquema completo y modelo de seguridad (documento de referencia)
-- Fecha: 2026-09-13
--
-- QUÉ ES: la definición completa de las 8 tablas, las funciones de permisos,
-- los disparadores (triggers), las políticas de RLS (Row Level Security) y
-- los permisos de rol de este proyecto, tal como están hoy. Se armó
-- extrayendo la definición real de cada objeto con pg_get_functiondef() /
-- pg_get_constraintdef() y las policies de pg_policy, no de memoria: es
-- exactamente lo que hay, no una aproximación.
--
-- PARA QUÉ SIRVE: la aplicación en sí (el código en `js/`) no puede mostrar
-- esto -- corre en el navegador de cada usuario, y la barrera real de
-- permisos vive en la base de datos, no en la pantalla. Este archivo es la
-- forma de verificar esa afirmación sin necesitar acceso directo a la base:
-- cada tabla tiene RLS activa, cada política está escrita acá tal cual existe,
-- y las funciones que corren con privilegios elevados (`security definer`)
-- fijan `search_path` para no quedar expuestas al ataque clásico de ese
-- patrón en Postgres.
--
-- Los datos de ejemplo del PASO 6 son registros fabricados para pruebas: ningún
-- nombre, teléfono, mail o fecha de nacimiento corresponde a una persona real.
--
-- No pensado para correrse de nuevo tal cual contra una base que ya tiene
-- estas tablas -- los "create table" fallarían porque ya existen. Es
-- documentación, no un script de instalación.
-- ============================================================================


