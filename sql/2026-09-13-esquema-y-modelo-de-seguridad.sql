-- productores
create policy productores_select_todos on public.productores for select to authenticated
  using (exists (select 1 from usuarios u where u.id = auth.uid()));
create policy productores_admin_edita_todo on public.productores for all to authenticated
  using (mi_rol() = 'admin') with check (mi_rol() = 'admin');
create policy productores_editor_inserta_su_dupla on public.productores for insert to authenticated
  with check (mi_rol() = 'editor' and tiene_dupla(ejecutivo));
create policy productores_editor_edita_su_dupla on public.productores for update to authenticated
  using (mi_rol() = 'editor' and tiene_dupla(ejecutivo)) with check (mi_rol() = 'editor' and tiene_dupla(ejecutivo));
create policy carga_pas_inserta_su_dupla on public.productores for insert to authenticated
  with check (mi_rol() = 'carga_pas' and tiene_dupla(ejecutivo));
create policy carga_pas_edita_su_dupla on public.productores for update to authenticated
  using (mi_rol() = 'carga_pas' and tiene_dupla(ejecutivo));

-- producciones
create policy producciones_select_todos on public.producciones for select to authenticated
  using (exists (select 1 from usuarios u where u.id = auth.uid()));
create policy producciones_admin_edita_todo on public.producciones for all to authenticated
  using (mi_rol() = 'admin') with check (mi_rol() = 'admin');
create policy producciones_editor_gestiona_su_dupla on public.producciones for all to authenticated
  using (mi_rol() = 'editor' and exists (select 1 from productores p where p.id = producciones.pas_id and tiene_dupla(p.ejecutivo)))
  with check (mi_rol() = 'editor' and exists (select 1 from productores p where p.id = producciones.pas_id and tiene_dupla(p.ejecutivo)));

-- produccion_companias
create policy detalle_select_todos on public.produccion_companias for select to authenticated
  using (exists (select 1 from usuarios u where u.id = auth.uid()));
create policy detalle_admin_edita_todo on public.produccion_companias for all to authenticated
  using (mi_rol() = 'admin') with check (mi_rol() = 'admin');
create policy detalle_editor_gestiona_su_dupla on public.produccion_companias for all to authenticated
  using (mi_rol() = 'editor' and exists (select 1 from producciones pr join productores p on p.id = pr.pas_id where pr.id = produccion_companias.produccion_id and tiene_dupla(p.ejecutivo)))
  with check (mi_rol() = 'editor' and exists (select 1 from producciones pr join productores p on p.id = pr.pas_id where pr.id = produccion_companias.produccion_id and tiene_dupla(p.ejecutivo)));

-- catalogos
